/** A value followed by a space when it ends in Latin text or digits, as Japanese prose spaces them. */
const sp = (value) => (/[\x21-\x7e]$/.test(String(value)) ? `${value} ` : String(value));
/** A value preceded by a space when it starts with Latin text or digits. */
const ps = (value) => (/^[\x21-\x7e]/.test(String(value)) ? ` ${value}` : String(value));

