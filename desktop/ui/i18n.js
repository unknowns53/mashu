const LANGUAGES = [
  ["ja", "日本語"],
  ["en", "English"],
];

function savedLanguage() {
  try {
    const saved = localStorage.getItem("mashu.language");
    if (saved && STRINGS[saved]) return saved;
  } catch (error) {
    // Storage may be unavailable; the default below still works.
  }
  return (navigator.language || "").toLowerCase().startsWith("ja") ? "ja" : "en";
}

let language = savedLanguage();

function setLanguage(next) {
  language = STRINGS[next] ? next : "en";
  try {
    localStorage.setItem("mashu.language", language);
  } catch (error) {
    // Kept for this window only.
  }
  document.documentElement.lang = language;
}

/** The label for a key, filled with vars; an unknown key shows itself so it is noticed. */
function t(key, vars = {}) {
  const entry = STRINGS[language][key] ?? STRINGS.en[key];
  if (entry === undefined) return key;
  return typeof entry === "function" ? entry(vars) : entry;
}

/** A label for a stored value (an outcome, a kind…), or the value itself when unnamed. */
function named(prefix, value) {
  if (value === null || value === undefined || value === "") return "";
  const key = `${prefix}.${value}`;
  const entry = STRINGS[language][key] ?? STRINGS.en[key];
  return entry === undefined ? String(value) : t(key);
}

document.documentElement.lang = language;
